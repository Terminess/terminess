#!/usr/bin/env python3
"""Generate Sources/TermCore/CharWidthTables.swift from Unicode Character Database files.

Usage: gen-width.py UCD_DIR OUT_FILE
UCD_DIR must contain EastAsianWidth.txt, emoji-data.txt and DerivedGeneralCategory.txt
(from https://www.unicode.org/Public/<version>/ucd/).

Width rules:
  0  general category Mn, Me or Cf (except U+00AD soft hyphen), and Hangul medial
     vowels and final consonants (U+1160 to U+11FF, U+D7B0 to U+D7FF)
  2  East Asian Width W or F, or Emoji_Presentation=Yes
  1  everything else (ambiguous width counts as narrow)
"""
import re
import sys
from pathlib import Path

LINE = re.compile(r"^([0-9A-F]+)(?:\.\.([0-9A-F]+))?\s*;\s*([A-Za-z_]+)")


def ranges(path, wanted):
    out = []
    for line in Path(path).read_text(encoding="utf-8").splitlines():
        m = LINE.match(line)
        if m and m.group(3) in wanted:
            lo = int(m.group(1), 16)
            hi = int(m.group(2) or m.group(1), 16)
            out.append((lo, hi))
    return out


def merge(rs):
    rs = sorted(rs)
    out = []
    for lo, hi in rs:
        if out and lo <= out[-1][1] + 1:
            out[-1] = (out[-1][0], max(out[-1][1], hi))
        else:
            out.append((lo, hi))
    return out


def subtract(rs, holes):
    """Remove every codepoint in holes from rs."""
    hole_set = set()
    for lo, hi in holes:
        hole_set.update(range(lo, hi + 1))
    out = []
    for lo, hi in rs:
        start = None
        for cp in range(lo, hi + 2):
            inside = cp <= hi and cp not in hole_set
            if inside and start is None:
                start = cp
            elif not inside and start is not None:
                out.append((start, cp - 1))
                start = None
    return merge(out)


def version(path):
    first = Path(path).read_text(encoding="utf-8").splitlines()[0]
    m = re.search(r"(\d+\.\d+\.\d+)", first)
    return m.group(1) if m else "unknown"


def emit(name, rs):
    body = ",\n".join(f"    (0x{lo:05X}, 0x{hi:05X})" for lo, hi in rs)
    return f"let {name}: [(UInt32, UInt32)] = [\n{body},\n]\n"


def main():
    ucd, out = Path(sys.argv[1]), Path(sys.argv[2])
    zero = ranges(ucd / "DerivedGeneralCategory.txt", {"Mn", "Me", "Cf"})
    zero += [(0x1160, 0x11FF), (0xD7B0, 0xD7FF)]
    zero = subtract(merge(zero), [(0x00AD, 0x00AD)])
    wide = ranges(ucd / "EastAsianWidth.txt", {"W", "F"})
    wide += ranges(ucd / "emoji-data.txt", {"Emoji_Presentation"})
    wide = subtract(merge(wide), zero)
    ver = version(ucd / "EastAsianWidth.txt")
    text = (
        "// Generated by scripts/gen-width.py from Unicode " + ver + " data. Do not edit.\n"
        "// Unicode data: Copyright (c) Unicode, Inc. See NOTICE.\n\n"
        f"let unicodeDataVersion = \"{ver}\"\n\n"
        + emit("zeroWidthRanges", zero) + "\n" + emit("wideRanges", wide)
    )
    out.write_text(text, encoding="utf-8")
    print(f"Unicode {ver}: {len(zero)} zero-width ranges, {len(wide)} wide ranges -> {out}")


if __name__ == "__main__":
    main()
